-- Row-Level Security: defense in depth behind the Prisma tenant extension.
-- The API connects as the non-owner role erp_app, and its pool sets app.tenant_id
-- (and app.rls_bypass for the system context) on every connection, see
-- src/prisma/tenant-pool.ts. The owner (migrations, backups) and superusers are not
-- bound by these policies. With no setting, a query returns no rows and writes fail.

ALTER TABLE "tenants" ENABLE ROW LEVEL SECURITY;
CREATE POLICY "tenant_isolation" ON "tenants"
  USING ("id" = NULLIF(current_setting('app.tenant_id', true), '')::uuid
         OR current_setting('app.rls_bypass', true) = 'on')
  WITH CHECK ("id" = NULLIF(current_setting('app.tenant_id', true), '')::uuid
         OR current_setting('app.rls_bypass', true) = 'on');

