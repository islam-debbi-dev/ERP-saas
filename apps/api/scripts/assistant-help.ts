/**
 * Compiles the help articles and the web's route list into one TS file, so the API needs
 * no file on disk at runtime (`nest build` copies no .md, Vercel would not trace them, and
 * the API cannot read apps/web). A test fails if the bundle is stale.
 *
 * Usage: pnpm --filter @erp/api assistant:help
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export const HELP_DIR = path.join(__dirname, '..', 'src', 'assistant', 'help');
export const BUNDLE_FILE = path.join(HELP_DIR, 'help-bundle.ts');
export const WEB_APP_DIR = path.join(__dirname, '..', '..', 'web', 'src', 'app');

export interface HelpArticle {
  slug: string;
  language: 'fr' | 'ar';
  title: string;
  feature: string | null;
  body: string;
}

function parseArticle(slug: string, language: HelpArticle['language'], text: string): HelpArticle {
  const match = /^---\n([\s\S]*?)\n---\n\n([\s\S]*)$/.exec(text);
  if (!match?.[1] || !match[2]) throw new Error(`Bad front matter in ${language}/${slug}`);
  const field = (name: string) =>
    new RegExp(`^${name}: (.+)$`, 'm').exec(match[1] ?? '')?.[1]?.trim() ?? null;
  const title = field('title');
  if (!title) throw new Error(`No title in ${language}/${slug}`);
  return { slug, language, title, feature: field('feature'), body: match[2].trim() };
}

export function readArticles(): HelpArticle[] {
  return (['fr', 'ar'] as const).flatMap((language) =>
    readdirSync(path.join(HELP_DIR, language))
      .filter((f) => f.endsWith('.md'))
      .sort()
      .map((f) =>
        parseArticle(
          f.replace(/\.md$/, ''),
          language,
          readFileSync(path.join(HELP_DIR, language, f), 'utf8'),
        ),
      ),
  );
}

/** Every screen of the app: `(group)` folders vanish, `[id]` stays as a pattern. */
export function readWebRoutes(dir = WEB_APP_DIR, prefix = ''): string[] {
  return readdirSync(dir, { withFileTypes: true })
    .flatMap((entry) => {
      if (entry.isFile()) return entry.name === 'page.tsx' ? [prefix || '/'] : [];
      if (!entry.isDirectory()) return [];
      const group = /^\(.*\)$/.test(entry.name);
      return readWebRoutes(
        path.join(dir, entry.name),
        group ? prefix : `${prefix}/${entry.name}`,
      );
    })
    .sort();
}

export function renderBundle(): string {
  const routes = readWebRoutes().filter((r) => !r.startsWith('/admin') && !r.startsWith('/s/'));
  return `// Generated by scripts/assistant-help.ts. Do not edit: change the .md files and run
// \`pnpm --filter @erp/api assistant:help\`.
import type { HelpArticle } from './help-articles';

export const HELP_ARTICLES: readonly HelpArticle[] = ${JSON.stringify(readArticles(), null, 2)};

export const WEB_ROUTES: readonly string[] = ${JSON.stringify(routes, null, 2)};
`;
}

if (require.main === module) {
  writeFileSync(BUNDLE_FILE, renderBundle());
  console.log(`Wrote ${path.relative(process.cwd(), BUNDLE_FILE)}`);
}
