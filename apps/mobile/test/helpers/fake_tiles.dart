/// Tiles from memory: map tests never touch the network. Counts the tiles
/// asked for, so a test can see the map really drew.
class FakeTileProvider extends TileProvider {
  static int requested = 0;

  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) {
    requested++;
    return MemoryImage(_png);
  }
}

/// Every map in the test uses [FakeTileProvider].
void useFakeTiles() {
  MapTiles.testProvider = FakeTileProvider.new;
}
